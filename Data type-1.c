/*Write programme that prints an integer number, floating number, double number and character*/
#include <stdio.h>
int main() 
{
    int num1= 10;
    int num2 = 20;
    printf("Number is: %d\n", num1);
    printf("Number is: %d\n", num2);
    float num3 = 10.5;
    double num4 = 20.522467;
    char ch = 'A';
    printf("Number is: %f\n", num3);
    printf("Number is: %lf\n", num4);
    printf("Character is: %c\n", ch);
    return 0;
}
